#!/usr/bin/env python3
"""Convert a HyDE kitty theme into a Ghostty colour config."""
from __future__ import annotations

import argparse
import os
import re
import sys

COLOR_RE = re.compile(r"^\s*([A-Za-z0-9_]+)\s+(#(?:[0-9a-fA-F]{3,8}))\s*$")

BASE_MAP = {
    "foreground": "foreground",
    "background": "background",
    "selection_foreground": "selection-foreground",
    "selection_background": "selection-background",
    "cursor": "cursor-color",
    "cursor_text_color": "cursor-text",
}


def normalise_hex(value: str) -> str:
    digits = value.lstrip("#")
    if len(digits) == 3:
        digits = "".join(ch * 2 for ch in digits)
    if len(digits) == 8:
        digits = digits[:6]
    return "#" + digits.lower()


def convert(path: str, theme_name: str) -> str:
    lines = [
        "# Generated by HyDE -> Ghostty bridge. Do not edit by hand.",
        f"# HyDE theme: {theme_name}",
        "",
    ]
    palette: dict[int, str] = {}
    found_base = False
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            for raw in handle:
                line = raw.rstrip("\n")
                if line.startswith("#") or not line.strip():
                    continue
                if line.startswith("$"):
                    continue
                stripped = line.strip()
                if stripped.startswith("color") and " " in stripped:
                    key, _, value = stripped.partition(" ")
                    if key[5:].isdigit() and value.strip().startswith("#"):
                        index = int(key[5:])
                        if 0 <= index <= 15:
                            palette[index] = normalise_hex(value.strip())
                        continue
                match = COLOR_RE.match(line)
                if not match:
                    continue
                key, value = match.group(1), normalise_hex(match.group(2))
                target = BASE_MAP.get(key)
                if target:
                    lines.append(f"{target} = {value}")
                    found_base = True
    except OSError:
        pass
    if palette:
        lines.append("")
        for index in range(16):
            if index in palette:
                lines.append(f"palette = {index}={palette[index]}")
        found_base = True
    if not found_base:
        return ""
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--kitty-theme", default="")
    parser.add_argument("--theme-dir", default="")
    parser.add_argument("--theme-name", default=os.environ.get("HYDE_THEME", "HyDE"))
    parser.add_argument("--out", default=os.path.expanduser("~/.config/ghostty/hyde-theme.conf"))
    args = parser.parse_args()

    source = args.kitty_theme
    if not source and args.theme_dir:
        candidate = os.path.join(args.theme_dir, "kitty.theme")
        if os.path.isfile(candidate):
            source = candidate
    if not source or not os.path.isfile(source):
        print("ghostty-sync: no kitty theme found", file=sys.stderr)
        return 1
    content = convert(source, args.theme_name)
    if not content:
        print("ghostty-sync: kitty theme had no colours", file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(content)
    print(f"ghostty-sync: wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
